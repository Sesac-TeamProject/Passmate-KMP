enum StudentAvatars {
    static let count = 12

    static let defaultId = 1

    static let ids = Array(1...count)
}

struct StudentAvatarView: View {
    let avatarId: Int

    private var resolvedId: Int {
        if avatarId >= 1 && avatarId <= StudentAvatars.count {
            return avatarId
        } else {
            return StudentAvatars.defaultId
        }
    }

    var body: some View {
        GeometryReader { geometry in
            let scale = min(geometry.size.width, geometry.size.height) / 36
            let shapes = studentAvatarShapes[resolvedId] ?? []

            ZStack {
                ForEach(Array(shapes.enumerated()), id: \.offset) { _, shape in
                    shapeView(shape, scale: scale)
                }
            }
        }
    }

    @ViewBuilder
    private func shapeView(_ shape: AvatarShape, scale: CGFloat) -> some View {
        switch shape {
        case let .oval(cx, cy, rx, ry, hex):
            Path(
                ellipseIn: CGRect(
                    x: (cx - rx) * scale,
                    y: (cy - ry) * scale,
                    width: rx * 2 * scale,
                    height: ry * 2 * scale
                )
            )
            .fill(Color(avatarHex: hex))
        case let .polygon(points, hex):
            polygonPath(points, scale: scale)
                .fill(Color(avatarHex: hex))
        }
    }

    private func polygonPath(_ points: [(CGFloat, CGFloat)], scale: CGFloat) -> Path {
        Path { path in
            if let first = points.first {
                path.move(to: CGPoint(x: first.0 * scale, y: first.1 * scale))
                for point in points.dropFirst() {
                    path.addLine(to: CGPoint(x: point.0 * scale, y: point.1 * scale))
                }
                path.closeSubpath()
            }
        }
    }
}

enum AvatarShape {
    case oval(CGFloat, CGFloat, CGFloat, CGFloat, UInt32)
    case polygon([(CGFloat, CGFloat)], UInt32)
}

private extension Color {
    init(avatarHex hex: UInt32) {
        self.init(
            .sRGB,
            red: Double((hex >> 16) & 0xFF) / 255.0,
            green: Double((hex >> 8) & 0xFF) / 255.0,
            blue: Double(hex & 0xFF) / 255.0,
            opacity: 1.0
        )
    }
}

